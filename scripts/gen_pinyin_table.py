#!/usr/bin/env python3
"""Generate src/tasks/pinyin_table.inc — toneless pinyin for each CJK character.

    pip install pypinyin==0.55.0
    python scripts/gen_pinyin_table.py > src/tasks/pinyin_table.inc

Covers U+3400..U+9FFF (CJK Extension A + the URO) plus U+3007 (〇). Each
character gets its single most common reading, without tone; ü is written `v`
(pypinyin's NORMAL style). Characters pypinyin has no reading for map to 0.

A per-character table is enough for closed-set command matching: both the
command list and the recogniser output go through the same table, so a
polyphone reads the same on both sides. On the command benchmark it matched
exactly as well as pypinyin's phrase-aware conversion.

The reading data comes from pypinyin (MIT), which is built on the Unicode
Unihan database.
"""
import sys

import pypinyin
from pypinyin import Style, lazy_pinyin

FIRST, LAST = 0x3400, 0x9FFF
EXTRA = [0x3007]


def reading(cp):
    ch = chr(cp)
    p = lazy_pinyin(ch, style=Style.NORMAL, errors="ignore")
    if not p or p[0] == ch or not p[0].isascii() or not p[0].isalpha():
        return ""
    return p[0].lower()


def main():
    syllables = [""]  # 0 = no reading
    index = {"": 0}

    def sid(s):
        if s not in index:
            index[s] = len(syllables)
            syllables.append(s)
        return index[s]

    ids = [sid(reading(cp)) for cp in range(FIRST, LAST + 1)]
    extra = [(cp, sid(reading(cp))) for cp in EXTRA]
    assert len(syllables) < 65536
    covered = sum(1 for i in ids if i)

    w = sys.stdout.write
    w("// Generated by scripts/gen_pinyin_table.py from pypinyin %s (MIT, built on\n"
      "// Unicode Unihan). Do not edit by hand.\n" % pypinyin.__version__)
    w("// %d syllables; %d of %d characters in U+%04X..U+%04X have a reading.\n"
      % (len(syllables) - 1, covered, len(ids), FIRST, LAST))
    w("constexpr char32_t kPinyinFirst = 0x%04X;\n" % FIRST)
    w("constexpr char32_t kPinyinLast = 0x%04X;\n" % LAST)
    w("constexpr const char* kPinyinSyllables[] = {\n")
    for i in range(0, len(syllables), 12):
        w("    " + " ".join('"%s",' % s for s in syllables[i:i + 12]) + "\n")
    w("};\n")
    w("constexpr unsigned short kPinyinIndex[] = {\n")
    for i in range(0, len(ids), 24):
        w("    " + ",".join(str(v) for v in ids[i:i + 24]) + ",\n")
    w("};\n")
    w("struct PinyinExtra { char32_t cp; unsigned short id; };\n")
    w("constexpr PinyinExtra kPinyinExtra[] = {\n")
    for cp, i in extra:
        w("    {0x%04X, %d},\n" % (cp, i))
    w("};\n")


if __name__ == "__main__":
    main()
